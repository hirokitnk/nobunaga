export const LAND_XY = LAND.map((l) => ({ name: l.name, pts: l.pts.map(([lo, la]) => project(lo, la)) }));
export const LAKES_XY = LAKES.map((l) => ({ name: l.name, pts: l.pts.map(([lo, la]) => project(lo, la)) }));

export function pointInPoly(x, y, pts) {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const xi = pts[i][0], yi = pts[i][1], xj = pts[j][0], yj = pts[j][1];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export function isLand(x, y) {
  for (const l of LAKES_XY) if (pointInPoly(x, y, l.pts)) return false;
  for (const l of LAND_XY) if (pointInPoly(x, y, l.pts)) return true;
  return false;
}
